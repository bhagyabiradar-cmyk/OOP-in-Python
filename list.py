# Creating a list
fruits = ["Apple", "Banana", "Mango"]

# Accessing elements
print("First fruit:", fruits[0])

# Adding an element
fruits.append("Orange")
print("After adding:", fruits)

# Modifying an element
fruits[1] = "Grapes"
print("After modifying:", fruits)

# Removing an element
fruits.remove("Apple")
print("After removing:", fruits)